// Helper to determine the public server URL
function getServerUrl(req: Request): string {
  // Respect forwarded headers if running behind Cloud Run / reverse proxy
  const proto = (req.headers['x-forwarded-proto'] as string) || req.protocol || 'http';
  const host = (req.headers['x-forwarded-host'] as string) || req.get('host') || 'localhost:3000';
  return `${proto}://${host}`;
}

// ----------------------------------------------------
// SECURITY: OAuth & Token Authentication Middleware
// ----------------------------------------------------
export function verifyConnectorAuth(req: Request, res: Response, next: NextFunction) {
  const authHeader = req.headers.authorization;
  const customKeyHeader = req.headers['x-connector-key'];
  const queryToken = req.query.token as string | undefined;

  let providedToken = '';

  if (authHeader && authHeader.startsWith('Bearer ')) {
    providedToken = authHeader.slice(7).trim();
  } else if (typeof customKeyHeader === 'string') {
    providedToken = customKeyHeader.trim();
  } else if (queryToken) {
    providedToken = queryToken.trim();
  }

  if (!providedToken) {
    res.setHeader('WWW-Authenticate', 'Bearer realm="mido-ai-connector", error="invalid_token"');
    return res.status(401).json({
      error: 'Unauthorized',
      code: 'MISSING_TOKEN',
      message: 'Access denied: Valid OAuth Bearer Token or Mido AI Connector Key is required.',
      help: 'Authenticate via OAuth 2.0 (/oauth/authorize) or provide header "Authorization: Bearer <TOKEN>".',
      oauthDiscovery: '/.well-known/oauth-authorization-server',
      openapi: '/api/openapi.json'
    });
  }

  // Check 1: Is it a valid OAuth Access Token?
  const oauthTokenRecord = activeTokens.get(providedToken);
  if (oauthTokenRecord) {
    if (Date.now() > oauthTokenRecord.expiresAt) {
      activeTokens.delete(providedToken);
      res.setHeader('WWW-Authenticate', 'Bearer realm="mido-ai-connector", error="token_expired"');
      return res.status(401).json({
        error: 'Unauthorized',
        code: 'TOKEN_EXPIRED',
        message: 'Your OAuth Access Token has expired. Please refresh the token via /oauth/token.'
      });
    }
    // Token is valid!
    (req as any).connectorAuth = { type: 'oauth', ...oauthTokenRecord };
    return next();
  }

  // Check 2: Is it the active Mido Connector API Key?
  if (providedToken === currentMidoApiKey || providedToken === DEFAULT_SEED_TOKEN) {
    (req as any).connectorAuth = { type: 'apiKey', token: providedToken };
    return next();
  }

  // Invalid token
  res.setHeader('WWW-Authenticate', 'Bearer realm="mido-ai-connector", error="invalid_token"');
  return res.status(401).json({
    error: 'Unauthorized',
    code: 'INVALID_TOKEN',
    message: 'Access denied: The provided token is invalid or has been revoked.',
    help: 'Configure OAuth in ChatGPT using /oauth/authorize and /oauth/token or check the Mido AI settings.'
  });
}

