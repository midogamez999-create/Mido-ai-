// 3. OAUTH 2.0 TOKEN EXCHANGE ENDPOINT (POST)
// Standard RFC 6749 Token Endpoint
// ----------------------------------------------------
chatgptConnectorRouter.post('/oauth/token', (req: Request, res: Response) => {
  // Support both application/x-www-form-urlencoded and application/json
  const body = req.body || {};

  // Check HTTP Basic Authorization header for client_id:client_secret
  let clientId = body.client_id;
  let clientSecret = body.client_secret;

  const authHeader = req.headers.authorization;
  if (authHeader && authHeader.startsWith('Basic ')) {
    try {
      const decoded = Buffer.from(authHeader.slice(6), 'base64').toString('utf-8');
      const [bId, bSecret] = decoded.split(':');
      if (bId) clientId = bId;
      if (bSecret) clientSecret = bSecret;
    } catch {
      // Ignore basic auth decode error, fallback to body
    }
  }

  const grantType = body.grant_type;

  // Case A: authorization_code exchange
  if (grantType === 'authorization_code') {
    const code = body.code;
    if (!code) {
      return res.status(400).json({ error: 'invalid_request', error_description: 'Missing code parameter' });
    }

    const record = authCodes.get(code);
    if (!record) {
      return res.status(400).json({ error: 'invalid_grant', error_description: 'Authorization code is invalid or expired' });
    }

    if (Date.now() > record.expiresAt) {
      authCodes.delete(code);
      return res.status(400).json({ error: 'invalid_grant', error_description: 'Authorization code has expired' });
    }

    // PKCE code_verifier check if code_challenge was provided
    if (record.codeChallenge) {
      const codeVerifier = body.code_verifier;
      if (!codeVerifier) {
        return res.status(400).json({ error: 'invalid_grant', error_description: 'PKCE code_verifier required' });
      }
      if (record.codeChallengeMethod === 'S256') {
        const expectedChallenge = crypto.createHash('sha256').update(codeVerifier).digest('base64url');
        if (expectedChallenge !== record.codeChallenge) {
          return res.status(400).json({ error: 'invalid_grant', error_description: 'PKCE verification failed' });
        }
      } else if (codeVerifier !== record.codeChallenge) {
        return res.status(400).json({ error: 'invalid_grant', error_description: 'PKCE verification failed' });
      }
    }

    // Code is single use! Consume it immediately
    authCodes.delete(code);

    // Issue OAuth Access Token
    const accessToken = 'mido_oauth_at_' + crypto.randomBytes(24).toString('hex');
    const refreshToken = 'mido_oauth_rt_' + crypto.randomBytes(24).toString('hex');
    const expiresIn = 30 * 24 * 3600; // 30 days

    activeTokens.set(accessToken, {
      token: accessToken,
      clientId: record.clientId,
      scope: record.scope || 'mido:read mido:propose',
      createdAt: Date.now(),
      expiresAt: Date.now() + expiresIn * 1000,
      refreshToken
    });

    res.setHeader('Cache-Control', 'no-store');
    res.setHeader('Pragma', 'no-cache');
    return res.json({
      access_token: accessToken,
      token_type: 'Bearer',
      expires_in: expiresIn,
      refresh_token: refreshToken,
      scope: record.scope || 'mido:read mido:propose'
    });
  }

  // Case B: refresh_token exchange
  if (grantType === 'refresh_token') {
    const refreshToken = body.refresh_token;
    if (!refreshToken) {
      return res.status(400).json({ error: 'invalid_request', error_description: 'Missing refresh_token parameter' });
    }

    // Find token with matching refresh_token
    let matchedToken: AccessTokenRecord | undefined;
    let oldAccessTokenKey: string | undefined;
    for (const [key, val] of activeTokens.entries()) {
      if (val.refreshToken === refreshToken) {
        matchedToken = val;
        oldAccessTokenKey = key;
        break;
      }
    }

    if (!matchedToken || !oldAccessTokenKey) {
      return res.status(400).json({ error: 'invalid_grant', error_description: 'Invalid refresh_token' });
    }

    // Invalidate old token
    activeTokens.delete(oldAccessTokenKey);

    // Issue new token
    const newAccessToken = 'mido_oauth_at_' + crypto.randomBytes(24).toString('hex');
    const newRefreshToken = 'mido_oauth_rt_' + crypto.randomBytes(24).toString('hex');
    const expiresIn = 30 * 24 * 3600;

    activeTokens.set(newAccessToken, {
      token: newAccessToken,
      clientId: matchedToken.clientId,
      scope: matchedToken.scope,
      createdAt: Date.now(),
      expiresAt: Date.now() + expiresIn * 1000,
      refreshToken: newRefreshToken
    });

    res.setHeader('Cache-Control', 'no-store');
    return res.json({
      access_token: newAccessToken,
      token_type: 'Bearer',
      expires_in: expiresIn,
      refresh_token: newRefreshToken,
      scope: matchedToken.scope
    });
  }

  // Case C: client_credentials (convenient for automated testing or headless ChatGPT agents)
  if (grantType === 'client_credentials') {
    const newAccessToken = 'mido_oauth_at_' + crypto.randomBytes(24).toString('hex');
    const expiresIn = 30 * 24 * 3600;

    activeTokens.set(newAccessToken, {
      token: newAccessToken,
      clientId: clientId || OAUTH_CLIENT_ID,
      scope: 'mido:read mido:propose',
      createdAt: Date.now(),
      expiresAt: Date.now() + expiresIn * 1000
    });

    res.setHeader('Cache-Control', 'no-store');
    return res.json({
      access_token: newAccessToken,
      token_type: 'Bearer',
      expires_in: expiresIn,
      scope: 'mido:read mido:propose'
    });
  }

  return res.status(400).json({
    error: 'unsupported_grant_type',
    error_description: `Grant type "${grantType}" is not supported. Supported: authorization_code, refresh_token, client_credentials`
  });
});

// OAuth Revocation endpoint (RFC 7009)
chatgptConnectorRouter.post('/oauth/revoke', (req: Request, res: Response) => {
  const token = req.body?.token;
  if (token) {
    activeTokens.delete(token);
    for (const [key, val] of activeTokens.entries()) {
      if (val.refreshToken === token) {
        activeTokens.delete(key);
      }
    }
  }
  res.status(200).json({ success: true, message: 'Token revoked successfully' });
});

